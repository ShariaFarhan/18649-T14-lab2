static void *udp_rx_thread(void *arg) {
    (void)arg;
    int sock = socket(AF_INET, SOCK_DGRAM, 0);
    if (sock < 0) { perror("socket"); return NULL; }

    struct sockaddr_in addr = {0};
    addr.sin_family = AF_INET;
    addr.sin_addr.s_addr = INADDR_ANY;
    addr.sin_port = htons(UDP_PORT);

    if (bind(sock, (struct sockaddr *)&addr, sizeof(addr)) < 0) {
        perror("bind");
        close(sock);
        return NULL;
    }

    uint8_t packet[UDP_PACKET_LEN];

    while (g_running) {
        ssize_t n = recvfrom(sock, packet, sizeof(packet), 0, NULL, NULL);
        if (n < 0) {
            if (errno == EINTR) continue;
            perror("recvfrom");
            continue;
        }
        if (n != UDP_PACKET_LEN) {
            //not a well-formed wheel packet -- drop
            continue;
        }

        int32_t raw_lx, raw_ly, raw_lrz;
        memcpy(&raw_lx,  &packet[OFF_LX],  4);
        memcpy(&raw_ly,  &packet[OFF_LY],  4);
        memcpy(&raw_lrz, &packet[OFF_LRZ], 4);

        // TODO: range-check raw_lx/ly/lrz against part-1-recorded calibration bounds here 
        uint16_t buttons_mask;
        extract_buttons_mask(&packet[OFF_BUTTONS], &buttons_mask);

        pthread_mutex_lock(&g_state.lock);
        g_state.steering_raw = (int16_t)raw_lx;   // TODO: confirm truncation is acceptable 
        g_state.throttle_raw = (int16_t)raw_ly;
        g_state.brake_raw    = (int16_t)raw_lrz;
        g_state.buttons      = buttons_mask;
        clock_gettime(CLOCK_MONOTONIC, &g_state.last_udp_rx);
        g_state.have_udp_ever = 1;
        pthread_mutex_unlock(&g_state.lock);
    }

    close(sock);
    return NULL;
}


//------------------------------UDP TX thread------------------------------

static void *uart_tx_thread(void *arg) {
    int uart_fd = *(int *)arg;

    struct timespec next;
    clock_gettime(CLOCK_MONOTONIC, &next);

    while (g_running) {
        cmd_payload_t payload = {0};
        uint8_t seq;

        pthread_mutex_lock(&g_state.lock);

        int stale = !g_state.have_udp_ever ||
                    (ms_since(&g_state.last_udp_rx) > UDP_STALE_MS);

        if (stale) {
            payload.steering_raw = 0;
            payload.throttle_raw = 0;
            payload.brake_raw    = 0;
            payload.buttons      = 0;
            payload.flags        = FLAG_UDP_STALE;
        } else {
            payload.steering_raw = g_state.steering_raw;
            payload.throttle_raw = g_state.throttle_raw;
            payload.brake_raw    = g_state.brake_raw;
            payload.buttons      = g_state.buttons;
            payload.flags        = 0;
        }

        seq = g_state.tx_seq++;
        pthread_mutex_unlock(&g_state.lock);

        send_frame(uart_fd, seq, (uint8_t *)&payload, sizeof(payload));

        next.tv_nsec += CMD_PERIOD_MS * 1000000L;
        while (next.tv_nsec >= 1000000000L) {
            next.tv_nsec -= 1000000000L;
            next.tv_sec++;
        }
        clock_nanosleep(CLOCK_MONOTONIC, TIMER_ABSTIME, &next, NULL);
    }

    return NULL;
}

//------------------------------UDP RX thread: stm32 heartbeat------------------------------


typedef enum {
    PARSE_SCAN_START0,
    PARSE_SCAN_START1,
    PARSE_LEN,
    PARSE_SEQ,
    PARSE_PAYLOAD,
    PARSE_CRC0,
    PARSE_CRC1,
} parse_state_t;

static void *uart_rx_thread(void *arg) {
    int uart_fd = *(int *)arg;

    parse_state_t state = PARSE_SCAN_START0;
    uint8_t payload_buf[MAX_PAYLOAD];
    uint8_t len = 0, seq = 0, payload_idx = 0;
    uint16_t crc_rx = 0;
    struct timespec frame_start_time;
    int in_frame = 0;

    int have_last_seq = 0;
    uint8_t last_seq = 0;

    while (g_running) {
        uint8_t byte;
        ssize_t n = read(uart_fd, &byte, 1);

        if (n <= 0) {
            // VTIME timeout doubles as chance to check for a stalled mid-frame parse
            if (in_frame && ms_since(&frame_start_time) > MID_FRAME_TIMEOUT_MS) {
                state = PARSE_SCAN_START0;
                in_frame = 0;
            }
            continue;
        }

        switch (state) {
        case PARSE_SCAN_START0:
            if (byte == FRAME_START0) {
                state = PARSE_SCAN_START1;
                clock_gettime(CLOCK_MONOTONIC, &frame_start_time);
                in_frame = 1;
            }
            break;

        case PARSE_SCAN_START1:
            if (byte == FRAME_START1) {
                state = PARSE_LEN;
            } else {
                //false positive on START0 -- resync, but don't lose genuine START0 that happens to be this byte
                state = (byte == FRAME_START0) ? PARSE_SCAN_START1 : PARSE_SCAN_START0;
                if (state == PARSE_SCAN_START0) in_frame = 0;
            }
            break;

        case PARSE_LEN:
            if (byte > MAX_PAYLOAD) {
                //implausible length -- this wasn't a real frame
                state = PARSE_SCAN_START0;
                in_frame = 0;
                break;
            }
            len = byte;
            payload_idx = 0;
            state = PARSE_SEQ;
            break;

        case PARSE_SEQ:
            seq = byte;
            state = (len > 0) ? PARSE_PAYLOAD : PARSE_CRC0;
            break;

        case PARSE_PAYLOAD:
            payload_buf[payload_idx++] = byte;
            if (payload_idx == len) state = PARSE_CRC0;
            break;

        case PARSE_CRC0:
            crc_rx = byte;
            state = PARSE_CRC1;
            break;

        case PARSE_CRC1: {
            crc_rx |= ((uint16_t)byte << 8);

            uint8_t crc_region[1 + 1 + MAX_PAYLOAD];
            crc_region[0] = len;
            crc_region[1] = seq;
            memcpy(&crc_region[2], payload_buf, len);
            uint16_t crc_calc = crc16_ccitt(0xFFFF, crc_region, 2 + len);

            if (crc_calc == crc_rx && len == sizeof(hb_payload_t)) {
                hb_payload_t hb;
                memcpy(&hb, payload_buf, sizeof(hb));

                pthread_mutex_lock(&g_state.lock);
                g_state.last_hb = hb;
                clock_gettime(CLOCK_MONOTONIC, &g_state.last_hb_rx);
                g_state.have_hb_ever = 1;
                pthread_mutex_unlock(&g_state.lock);

                if (have_last_seq && (uint8_t)(seq - last_seq) != 1) {
                    // TODO: gap detected -- log/count for writeup, no recovery action needed; this is detection only since no ARQ
                }
                last_seq = seq;
                have_last_seq = 1;
            }
            // CRC fail or size mismatch, silently drop, no NACK

            state = PARSE_SCAN_START0;
            in_frame = 0;
            break;
        }
        }
    }

    return NULL;
}


//----------------------------main-----------------------------------------------

int main(void) {
    int uart_fd = uart_open(UART_DEV, UART_BAUD);
    if (uart_fd < 0) return 1;

    pthread_t t_udp, t_tx, t_rx;
    pthread_create(&t_udp, NULL, udp_rx_thread, NULL);
    pthread_create(&t_tx,  NULL, uart_tx_thread, &uart_fd);
    pthread_create(&t_rx,  NULL, uart_rx_thread, &uart_fd);

    /* TODO: signal handling (SIGINT/SIGTERM) to set g_running=0 for
     * clean shutdown, and somewhere to surface g_state.last_hb (zone
     * state+currents)--stdout print, log file, or a debug socket. */

    pthread_join(t_udp, NULL);
    pthread_join(t_tx, NULL);
    pthread_join(t_rx, NULL);

    close(uart_fd);
    return 0;
}